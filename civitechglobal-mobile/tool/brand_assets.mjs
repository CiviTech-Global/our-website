#!/usr/bin/env node
/**
 * Builds every Android icon and splash resource from one file:
 * assets/brand/logo.svg, the vector trace of the company's logo.
 *
 * Usage (from the repository root, after `npm ci` in civitechglobal-web,
 * whose puppeteer-core renders the PNGs):
 *
 *   node civitechglobal-mobile/tool/brand_assets.mjs
 *
 * Everything is rendered to PNG, one per density, never written as an
 * Android vector drawable. The traced logo is a single path of some 40 KB,
 * and Android's VectorDrawable loader gives up on it: on a Galaxy S21 FE the
 * launcher logged "Failure retrieving resources ... mipmap/ic_launcher" and
 * drew the system's placeholder robot instead, and the splash screen came
 * up empty. A PNG cannot fail that way.
 *
 * What it writes:
 * - mipmap-<density>/ic_launcher_foreground.png: the adaptive icon's
 *   foreground (Android 8+), the logo inside the 66dp safe zone of the 108dp
 *   canvas so no launcher mask clips it.
 * - mipmap-<density>/ic_launcher_monochrome.png: the themed icon (Android
 *   13+). Only its alpha matters; the system supplies the colour.
 * - mipmap-anydpi-v26/ic_launcher.xml: the two on a pastel background.
 * - mipmap-<density>/ic_launcher.png: the flattened icon for Android 7.
 * - drawable[-night]-<density>/splash_logo.png and the launch themes: the
 *   logo centred on the theme's ground, light and dark, before Flutter
 *   draws its first frame.
 *
 * Colours are palette B (the default): the brand green on its pastel tint by
 * day, the lighter green on the night ground in dark mode.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const RES = join(ROOT, 'android', 'app', 'src', 'main', 'res');

const COLORS = {
  light: { ground: '#F1F7F0', logo: '#21763C', iconBackground: '#CDF1C5' },
  dark: { ground: '#060D07', logo: '#73C881' },
};

/** Android's density buckets, as pixels per dp. */
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };

const svg = readFileSync(join(ROOT, 'assets', 'brand', 'logo.svg'), 'utf8');

function write(relative, content) {
  const file = join(RES, relative);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log('wrote', relative);
}

// Vector drawables an earlier version of this script wrote; see above.
for (const stale of [
  'drawable/ic_launcher_foreground.xml',
  'drawable/ic_launcher_monochrome.xml',
  'drawable/splash_logo.xml',
]) {
  if (existsSync(join(RES, stale))) {
    rmSync(join(RES, stale));
    console.log('removed', stale);
  }
}

write(
  'mipmap-anydpi-v26/ic_launcher.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/brand_icon_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_monochrome" />
</adaptive-icon>
`
);

write(
  'values/brand_colors.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs: palette B (Pistachio & Pomegranate). Do not edit. -->
<resources>
    <color name="brand_ground">${COLORS.light.ground}</color>
    <color name="brand_icon_background">${COLORS.light.iconBackground}</color>
</resources>
`
);
write(
  'values-night/brand_colors.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. The launcher icon keeps
     its day colours: launchers do not switch icons with the theme. -->
<resources>
    <color name="brand_ground">${COLORS.dark.ground}</color>
</resources>
`
);

const launchBackground = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. The launch screen before
     Android 12: the theme's ground with the logo in the middle. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/brand_ground" />
    <item
        android:width="150dp"
        android:height="150dp"
        android:gravity="center"
        android:drawable="@drawable/splash_logo" />
</layer-list>
`;
write('drawable/launch_background.xml', launchBackground);
write('drawable-v21/launch_background.xml', launchBackground);

const normalTheme = `    <style name="NormalTheme" parent="@android:style/Theme.Light.NoTitleBar">
        <item name="android:windowBackground">@color/brand_ground</item>
    </style>`;
const styles = (parent, splash) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. -->
<resources>
    <style name="LaunchTheme" parent="${parent}">
        <item name="android:windowBackground">@drawable/launch_background</item>${splash}
    </style>
${normalTheme.replace('Theme.Light.NoTitleBar', parent.replace('@android:style/', ''))}
</resources>
`;
const splash12 = `
        <item name="android:windowSplashScreenBackground">@color/brand_ground</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_logo</item>`;
write('values/styles.xml', styles('@android:style/Theme.Light.NoTitleBar', ''));
write('values-night/styles.xml', styles('@android:style/Theme.Black.NoTitleBar', ''));
write('values-v31/styles.xml', styles('@android:style/Theme.Light.NoTitleBar', splash12));
write('values-night-v31/styles.xml', styles('@android:style/Theme.Black.NoTitleBar', splash12));

// ---- PNGs, rendered by a headless browser ----------------------------------
const require = createRequire(join(ROOT, '..', 'civitechglobal-web', 'package.json'));
const puppeteer = require('puppeteer-core');
const browserPath = [
  process.env.CHROME_PATH,
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/usr/bin/chromium',
  '/usr/bin/google-chrome',
].find((candidate) => candidate && existsSync(candidate));
if (!browserPath) throw new Error('No Chrome or Edge found. Set CHROME_PATH.');

/** The logo, `logoPx` square and in `color`, centred on a transparent `canvasPx` square. */
function scene(canvasPx, logoPx, color, background = 'transparent', radius = 0) {
  const logo = svg
    .replace('currentColor', color)
    .replace('<svg ', `<svg width="${logoPx}" height="${logoPx}" `);
  return `<body style="margin:0;background:transparent">
    <div style="width:${canvasPx}px;height:${canvasPx}px;border-radius:${radius}px;background:${background};display:grid;place-items:center">${logo}</div>
  </body>`;
}

const browser = await puppeteer.launch({ executablePath: browserPath, headless: true });
try {
  const page = await browser.newPage();
  async function render(relative, canvasPx, html) {
    await page.setViewport({ width: canvasPx, height: canvasPx, deviceScaleFactor: 1 });
    await page.setContent(html);
    const file = join(RES, relative);
    mkdirSync(dirname(file), { recursive: true });
    await page.screenshot({ path: file, omitBackground: true });
    console.log('wrote', relative);
  }

  for (const [density, scale] of Object.entries(DENSITIES)) {
    const px = (dp) => Math.round(dp * scale);
    // Adaptive layers: 108dp canvas, logo at 58dp, clear of the circular mask.
    await render(`mipmap-${density}/ic_launcher_foreground.png`, px(108), scene(px(108), px(58), COLORS.light.logo));
    await render(`mipmap-${density}/ic_launcher_monochrome.png`, px(108), scene(px(108), px(58), '#FFFFFF'));
    // Android 7: the whole icon on a rounded square, 48dp.
    await render(
      `mipmap-${density}/ic_launcher.png`,
      px(48),
      scene(px(48), px(34), COLORS.light.logo, COLORS.light.iconBackground, px(48) * 0.22)
    );
    // Splash: Android 12+ shows the icon inside a 160dp circle on a 240dp
    // canvas; the older launch screen draws the same image at 150dp.
    await render(`drawable-${density}/splash_logo.png`, px(240), scene(px(240), px(150), COLORS.light.logo));
    await render(`drawable-night-${density}/splash_logo.png`, px(240), scene(px(240), px(150), COLORS.dark.logo));
  }
} finally {
  await browser.close();
}
