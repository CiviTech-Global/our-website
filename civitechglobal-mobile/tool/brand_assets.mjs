#!/usr/bin/env node
/**
 * Builds every Android icon and splash resource from one file:
 * assets/brand/logo.svg, the vector trace of the company's logo.
 *
 * Usage (from the repository root, after `npm ci` in civitechglobal-web,
 * whose puppeteer-core renders the legacy PNGs):
 *
 *   node civitechglobal-mobile/tool/brand_assets.mjs
 *
 * What it writes, and why each exists:
 * - drawable/ic_launcher_foreground.xml: the adaptive icon's foreground
 *   (Android 8+). Vector, so it is sharp on every density. The logo sits
 *   inside the 66dp safe zone of the 108dp canvas, so no launcher mask
 *   clips it.
 * - drawable/ic_launcher_monochrome.xml: the themed icon (Android 13+). The
 *   same shape; the system supplies the colour.
 * - mipmap-anydpi-v26/ic_launcher.xml: ties the two together with a
 *   pastel background.
 * - mipmap-<density>/ic_launcher.png: the icon for Android 7, which has no
 *   adaptive icons (minSdk is 24).
 * - drawable/splash_logo.xml and the launch themes: the logo centred on the
 *   theme's ground, in light and in dark, before Flutter draws its first
 *   frame.
 *
 * Colours are palette B (the default): the brand green on its pastel tint by
 * day, the lighter green on the night ground in dark mode.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const RES = join(ROOT, 'android', 'app', 'src', 'main', 'res');

const COLORS = {
  light: { ground: '#F1F7F0', logo: '#21763C', iconBackground: '#CDF1C5' },
  dark: { ground: '#060D07', logo: '#73C881' },
};

const svg = readFileSync(join(ROOT, 'assets', 'brand', 'logo.svg'), 'utf8');
const pathData = /\sd="([^"]+)"/.exec(svg)[1];
const [, , vw, vh] = /viewBox="([^"]+)"/.exec(svg)[1].split(/\s+/).map(Number);

function write(relative, content) {
  const file = join(RES, relative);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log('wrote', relative);
}

/** A vector drawable holding the logo at `size` dp, centred on a `canvas` dp square. */
function vector(canvas, size, fill) {
  const scale = size / Math.max(vw, vh);
  const dx = (canvas - vw * scale) / 2;
  const dy = (canvas - vh * scale) / 2;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs from assets/brand/logo.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${canvas}dp"
    android:height="${canvas}dp"
    android:viewportWidth="${canvas}"
    android:viewportHeight="${canvas}">
    <group
        android:scaleX="${scale.toFixed(5)}"
        android:scaleY="${scale.toFixed(5)}"
        android:translateX="${dx.toFixed(3)}"
        android:translateY="${dy.toFixed(3)}">
        <path
            android:fillColor="${fill}"
            android:fillType="evenOdd"
            android:pathData="${pathData}" />
    </group>
</vector>
`;
}

// Adaptive icon: 108dp canvas, 66dp safe zone. 58dp keeps the bird's crest
// clear of the tightest (circular) mask.
write('drawable/ic_launcher_foreground.xml', vector(108, 58, '@color/brand_logo_on_icon'));
write('drawable/ic_launcher_monochrome.xml', vector(108, 58, '#FFFFFFFF'));
write(
  'mipmap-anydpi-v26/ic_launcher.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/brand_icon_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`
);

// Splash: Android 12+ draws the icon inside a 160dp circle on a 240dp canvas;
// the older launch screen centres the same drawable.
write('drawable/splash_logo.xml', vector(240, 150, '@color/brand_logo'));

write(
  'values/brand_colors.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs: palette B (Pistachio & Pomegranate). Do not edit. -->
<resources>
    <color name="brand_ground">${COLORS.light.ground}</color>
    <color name="brand_logo">${COLORS.light.logo}</color>
    <color name="brand_logo_on_icon">${COLORS.light.logo}</color>
    <color name="brand_icon_background">${COLORS.light.iconBackground}</color>
</resources>
`
);
write(
  'values-night/brand_colors.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. The launcher icon keeps
     its day colours: launchers do not switch icons with the theme. -->
<resources>
    <color name="brand_ground">${COLORS.dark.ground}</color>
    <color name="brand_logo">${COLORS.dark.logo}</color>
</resources>
`
);

const launchBackground = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. The launch screen before
     Android 12: the theme's ground with the logo in the middle. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@color/brand_ground" />
    <item
        android:width="150dp"
        android:height="150dp"
        android:gravity="center"
        android:drawable="@drawable/splash_logo" />
</layer-list>
`;
write('drawable/launch_background.xml', launchBackground);
write('drawable-v21/launch_background.xml', launchBackground);

const normalTheme = `    <style name="NormalTheme" parent="@android:style/Theme.Light.NoTitleBar">
        <item name="android:windowBackground">@color/brand_ground</item>
    </style>`;
const styles = (parent, splash) => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/brand_assets.mjs. Do not edit. -->
<resources>
    <style name="LaunchTheme" parent="${parent}">
        <item name="android:windowBackground">@drawable/launch_background</item>${splash}
    </style>
${normalTheme.replace('Theme.Light.NoTitleBar', parent.replace('@android:style/', ''))}
</resources>
`;
const splash12 = `
        <item name="android:windowSplashScreenBackground">@color/brand_ground</item>
        <item name="android:windowSplashScreenAnimatedIcon">@drawable/splash_logo</item>`;
write('values/styles.xml', styles('@android:style/Theme.Light.NoTitleBar', ''));
write('values-night/styles.xml', styles('@android:style/Theme.Black.NoTitleBar', ''));
write('values-v31/styles.xml', styles('@android:style/Theme.Light.NoTitleBar', splash12));
write('values-night-v31/styles.xml', styles('@android:style/Theme.Black.NoTitleBar', splash12));

// Legacy PNG icons for Android 7: the adaptive design flattened onto a
// rounded square, rendered by a headless browser.
const require = createRequire(join(ROOT, '..', 'civitechglobal-web', 'package.json'));
const puppeteer = require('puppeteer-core');
const browserPath = [
  process.env.CHROME_PATH,
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  '/usr/bin/chromium',
  '/usr/bin/google-chrome',
].find((candidate) => candidate && (() => { try { readFileSync(candidate); return true; } catch { return false; } })());
if (!browserPath) throw new Error('No Chrome or Edge found. Set CHROME_PATH.');

const browser = await puppeteer.launch({ executablePath: browserPath, headless: true });
try {
  const page = await browser.newPage();
  const densities = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
  for (const [density, px] of Object.entries(densities)) {
    await page.setViewport({ width: px, height: px, deviceScaleFactor: 1 });
    const logo = svg
      .replace('currentColor', COLORS.light.logo)
      .replace('<svg ', `<svg width="${Math.round(px * 0.7)}" height="${Math.round(px * 0.7)}" `);
    await page.setContent(
      `<body style="margin:0;background:transparent">
        <div style="width:${px}px;height:${px}px;border-radius:${px * 0.22}px;background:${COLORS.light.iconBackground};display:grid;place-items:center">${logo}</div>
      </body>`
    );
    const file = join(RES, `mipmap-${density}`, 'ic_launcher.png');
    await page.screenshot({ path: file, omitBackground: true });
    console.log('wrote', `mipmap-${density}/ic_launcher.png`);
  }
} finally {
  await browser.close();
}
