import 'dotenv/config';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { KavenegarClient, KavenegarError } from './services/sms/kavenegar.js';
import { SMS_TEMPLATES } from './services/sms/templates.js';

/**
 * Checking the SMS gateway before trusting it.
 *
 *   npm run sms:check                       account/info: remaining credit. Sends nothing.
 *   npm run sms:check -- --send 09121234567 one test code through SMS_OTP_TEMPLATE.
 *   npm run sms:check -- --templates        write guides/kavenegar-templates.md.
 *
 * Reads SMS_API_KEY and SMS_OTP_TEMPLATE from the environment (.env locally).
 * In production: docker exec civitech-api-1 node dist/sms-cli.js [--send 09…]
 * The key is never printed.
 */

/** The guide to submitting the templates, generated so it matches the code. */
function templatesGuide(): string {
  const lines = [
    '# Kavenegar templates',
    '',
    'Generated by `npm run sms:check -- --templates` from',
    '`civitechglobal-server/src/services/sms/templates.ts`. Do not edit by hand.',
    '',
    'Submit each one in the Kavenegar panel (اعتبارسنجی / Verify → templates):',
    'the **name** exactly as written, the **text** exactly as written, type SMS.',
    'A text may only go out once its template is approved.',
    '',
    'Rules every text follows: **no links** (the code refuses to send one), and',
    'placeholders carry no spaces — multi-word values are joined with a',
    'zero-width non-joiner, which reads as ordinary Persian.',
    '',
  ];
  for (const [kind, template] of Object.entries(SMS_TEMPLATES)) {
    lines.push(`## ${template.name}`, '', `Used for: ${template.purpose} (kind \`${kind}\`)`, '', '```', template.text, '```', '');
    for (const [token, meaning] of Object.entries(template.tokens)) lines.push(`- \`%${token}\`: ${meaning}`);
    lines.push('');
  }
  return lines.join('\n');
}

async function main() {
  if (process.argv.includes('--templates')) {
    const target = resolve(process.cwd(), '../guides/kavenegar-templates.md');
    writeFileSync(target, templatesGuide());
    console.log(`Wrote ${target}`);
    return;
  }

  const key = (process.env.SMS_API_KEY ?? '').trim();
  const template = (process.env.SMS_OTP_TEMPLATE ?? '').trim();
  if (!key) throw new Error('SMS_API_KEY is not set.');

  const api = new KavenegarClient(key);
  const account = await api.accountInfo();
  console.log(`Key works. Remaining credit: ${account.remainCredit.toLocaleString('en-US')} Rials (${account.type ?? 'account'}).`);

  const sendIndex = process.argv.indexOf('--send');
  if (sendIndex === -1) return;

  const phone = process.argv[sendIndex + 1] ?? '';
  if (!/^09\d{9}$/.test(phone)) throw new Error('Give a mobile number as 09xxxxxxxxx after --send.');
  if (!template) throw new Error('SMS_OTP_TEMPLATE is not set.');

  const code = String(Math.floor(100000 + Math.random() * 900000));
  const sent = await api.verifyLookup(phone, { token: code }, template);
  console.log(
    `Sent code ${code} to ${phone.slice(0, 4)}…${phone.slice(-3)} through template "${template}"` +
      ` (message ${sent.messageId ?? "?"}, cost ${sent.cost ?? "?"} Rials).`,
  );
}

main().catch((error) => {
  console.error(error instanceof KavenegarError || error instanceof Error ? error.message : error);
  process.exitCode = 1;
});
